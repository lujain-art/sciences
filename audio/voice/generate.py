"""Render every character line in the game to a local MP3 voice clip.

Run from the project root (requires internet + edge-tts):
    python audio/voice/generate.py

Lines are extracted from js/*.js so the manifest keys match the game text
exactly. Output: audio/voice/<who>/<hash>.mp3 + audio/voice/manifest.js
"""

import asyncio
import hashlib
import json
import re
import sys
from pathlib import Path

import edge_tts
import lameenc
import miniaudio
import numpy as np
from mutagen.mp3 import MP3

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "audio" / "voice"

# Three clearly different voices: deep professor, bright bubble, high sneaky villain.
VOICES = {
    "mix": {"voice": "ar-SA-HamedNeural", "rate": "+8%", "pitch": "-10Hz"},
    "bubbles": {"voice": "ar-EG-SalmaNeural", "rate": "+18%", "pitch": "+45Hz"},
    "trouble": {"voice": "ar-EG-ShakirNeural", "rate": "+8%", "pitch": "+70Hz"},
}

LINE_RE = re.compile(
    r"\.(?:say|quip|_line|_finaleLine)\(\s*(?:token\s*,\s*)?'(mix|bubbles|trouble)'\s*,\s*'([^']+)'"
)


def collect_lines():
    seen = []
    keys = set()
    for name in ("missions.js", "scenes.js", "main.js"):
        source = (ROOT / "js" / name).read_text(encoding="utf-8")
        for who, text in LINE_RE.findall(source):
            if (who, text) in keys:
                continue
            keys.add((who, text))
            seen.append((who, text))
    return seen


def trim_silence(path):
    """Drop the long lead-in/tail edge-tts adds so lines start on the beat."""
    dec = miniaudio.decode_file(
        str(path), output_format=miniaudio.SampleFormat.SIGNED16
    )
    pcm = np.frombuffer(dec.samples, dtype=np.int16)
    channels = dec.nchannels
    frames = pcm.reshape(-1, channels)
    mono = frames.mean(axis=1) / 32768.0
    rate = dec.sample_rate
    window = max(1, int(rate * 0.02))
    envelope = np.convolve(np.abs(mono), np.ones(window) / window, "same")
    voiced = np.where(envelope > 0.012)[0]
    if len(voiced) < 2:
        return
    start = max(0, voiced[0] - int(rate * 0.12))
    end = min(len(mono), voiced[-1] + int(rate * 0.3))
    segment = frames[start:end]
    if channels > 1:
        segment = segment.mean(axis=1).astype(np.int16).reshape(-1, 1)
    encoder = lameenc.Encoder()
    encoder.set_bit_rate(64)
    encoder.set_in_sample_rate(rate)
    encoder.set_channels(1)
    encoder.set_quality(2)
    data = encoder.encode(segment.tobytes()) + encoder.flush()
    path.write_bytes(data)


async def render(who, text, target, attempt=1):
    cfg = VOICES[who]
    try:
        communicate = edge_tts.Communicate(
            text, cfg["voice"], rate=cfg["rate"], pitch=cfg["pitch"]
        )
        await communicate.save(str(target))
        if target.stat().st_size < 1500:
            raise RuntimeError("clip too small")
        trim_silence(target)
        return
    except Exception as exc:
        if attempt >= 4:
            raise
        await asyncio.sleep(1.2 * attempt)
        await render(who, text, target, attempt + 1)


async def main():
    lines = collect_lines()
    if not lines:
        print("No lines found", file=sys.stderr)
        return 1

    manifest = {}
    tasks = []
    for who, text in lines:
        folder = OUT / who
        folder.mkdir(parents=True, exist_ok=True)
        digest = hashlib.sha1(f"{who}\n{text}".encode("utf-8")).hexdigest()[:10]
        target = folder / f"{digest}.mp3"
        tasks.append(render(who, text, target))
        manifest.setdefault(who, {})[text] = {
            "f": f"audio/voice/{who}/{digest}.mp3"
        }

    sem = asyncio.Semaphore(3)

    async def guarded(coro):
        async with sem:
            await coro

    await asyncio.gather(*(guarded(t) for t in tasks))

    for who, entries in manifest.items():
        for text, info in entries.items():
            audio = MP3(str(ROOT / info["f"]))
            info["d"] = round(audio.info.length, 2)
        print(f"{who}: {len(entries)} clips")

    payload = json.dumps(manifest, ensure_ascii=False, indent=2)
    (OUT / "manifest.js").write_text(
        "/* Generated by audio/voice/generate.py - local Arabic voice clips */\n"
        "window.SQ_VOICE_CLIPS = " + payload + ";\n",
        encoding="utf-8",
    )
    total = sum(
        (ROOT / info["f"]).stat().st_size
        for entries in manifest.values()
        for info in entries.values()
    )
    print(f"total {len(lines)} clips, {total / 1024:.0f} KB")
    return 0


if __name__ == "__main__":
    raise SystemExit(asyncio.run(main()))
